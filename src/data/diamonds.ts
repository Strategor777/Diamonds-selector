export function formatStonePrice(
  amount: number,
  currency: PriceCurrency = 'USD'
): string {
  const formatted = Math.round(amount).toLocaleString('en-US');
  if (currency === 'RUB') return `${formatted} ₽`;
  if (currency === 'EUR') return `€${formatted}`;
  return `$${formatted}`;
}

export function getColorHexTint(
  color: string,
  colorFamily?: string
): { base: string; deep: string; facet: string } {
  const whiteMap: Record<string, string> = {
    D: '#F8FBFF',
    E: '#F9FBFF',
    F: '#FAFBFD',
    G: '#FCFBF7',
    H: '#FCF9F0',
    I: '#FAF5E6',
    J: '#F7F0D9',
  };

  const upper = color.trim().toUpperCase();
  if (whiteMap[upper]) {
    return { base: whiteMap[upper], deep: '#DCE2EC', facet: 'rgba(27, 54, 93, 0.24)' };
  }

  const hay = `${color} ${colorFamily || ''}`.toLowerCase();
  if (hay.includes('розов') || hay.includes('pink') || hay.includes('rose')) {
    return { base: '#FCE4EC', deep: '#E99EB8', facet: 'rgba(173, 20, 87, 0.24)' };
  }
  if (hay.includes('красн') || hay.includes('рубин') || hay.includes('red') || hay.includes('ruby')) {
    return { base: '#FFCDD2', deep: '#C62828', facet: 'rgba(136, 14, 30, 0.34)' };
  }
  if (hay.includes('син') || hay.includes('голуб') || hay.includes('сапфир') || hay.includes('blue') || hay.includes('aqua')) {
    return { base: '#DBEAFE', deep: '#3B82F6', facet: 'rgba(29, 78, 216, 0.32)' };
  }
  if (hay.includes('зел') || hay.includes('изумруд') || hay.includes('green') || hay.includes('mint')) {
    return { base: '#D1FAE5', deep: '#10B981', facet: 'rgba(4, 120, 87, 0.32)' };
  }
  if (hay.includes('жёлт') || hay.includes('желт') || hay.includes('yellow') || hay.includes('canary') || hay.includes('lemon')) {
    return { base: '#FEF3C7', deep: '#F59E0B', facet: 'rgba(180, 83, 9, 0.28)' };
  }
  if (hay.includes('оранж') || hay.includes('orange') || hay.includes('padparadscha')) {
    return { base: '#FFEDD5', deep: '#EA580C', facet: 'rgba(154, 52, 18, 0.28)' };
  }
  if (hay.includes('фиолет') || hay.includes('пурпур') || hay.includes('сирен') || hay.includes('purple') || hay.includes('violet') || hay.includes('amethyst')) {
    return { base: '#EDE9FE', deep: '#8B5CF6', facet: 'rgba(91, 33, 182, 0.30)' };
  }
  if (hay.includes('коньяч') || hay.includes('шампан') || hay.includes('корич') || hay.includes('brown') || hay.includes('champagne') || hay.includes('cognac')) {
    return { base: '#F5E6D3', deep: '#B48352', facet: 'rgba(120, 74, 36, 0.28)' };
  }
  if (hay.includes('чёрн') || hay.includes('черн') || hay.includes('сер') || hay.includes('black') || hay.includes('gray') || hay.includes('grey')) {
    return { base: '#CBD5E1', deep: '#334155', facet: 'rgba(15, 23, 42, 0.45)' };
  }

  return { base: '#F5F7FA', deep: '#CBD5E1', facet: 'rgba(27, 54, 93, 0.24)' };
}

export function getCertVerifyUrl(lab: CertLab, certNumber: string): string {
  const cleanNum = encodeURIComponent(certNumber.trim());
  const upper = String(lab).toUpperCase();
  if (upper === 'GIA') {
    return `https://www.gia.edu/report-check?reportno=${cleanNum}`;
  }
  if (upper === 'IGI') {
    return `https://www.igi.org/Verify-Your-Report/?r=${cleanNum}`;
  }
  if (upper === 'HRD') {
    return `https://my.hrdantwerp.com/?record_number=${cleanNum}`;
  }
  if (upper === 'GRS') {
    return `https://www.gemresearch.ch/verify/?report=${cleanNum}`;
  }
  return `https://www.gia.edu/report-check?reportno=${cleanNum}`;
}

