export const DEFAULT_PRICING_CONFIG: PricingConfig = {
  mode: 'multiplier',
  value: 1.25,
  roundingStep: 10,
  applyOnImport: true,
};

export function calculateClientPrice(
  costPrice: number,
  mode: PricingMode,
  value: number,
  roundingStep: number = 10
): number {
  const safeCost = Math.max(0, Number.isFinite(costPrice) ? costPrice : 0);
  if (safeCost === 0) return 0;

  const factor =
    mode === 'multiplier'
      ? Math.max(0.01, Number.isFinite(value) ? value : 1)
      : Math.max(0.01, 1 + (Number.isFinite(value) ? value : 0) / 100);

  const raw = safeCost * factor;
  const step = roundingStep > 1 ? roundingStep : 1;
  return Math.max(1, Math.round(raw / step) * step);
}

export function getEffectiveCostPrice(stone: Diamond): number {
  if (typeof stone.costPriceUsd === 'number' && stone.costPriceUsd > 0) {
    return stone.costPriceUsd;
  }
  return Math.max(1, Math.round((stone.priceUsd / DEFAULT_PRICING_CONFIG.value) / 10) * 10);
}

export function applyPricingToDiamond(
  stone: Diamond,
  config: PricingConfig
): Diamond {
  const costPriceUsd = getEffectiveCostPrice(stone);
  const priceUsd = calculateClientPrice(
    costPriceUsd,
    config.mode,
    config.value,
    config.roundingStep
  );
  return {
    ...stone,
    costPriceUsd,
    markupMode: config.mode,
    markupValue: config.value,
    priceUsd,
  };
}

export function extractFancyIntensity(colorText: string): string {
  const low = colorText.toLowerCase();
  if (low.includes('fancy vivid') || low.includes('vivid')) return 'Fancy Vivid';
  if (low.includes('fancy intense') || low.includes('intense')) return 'Fancy Intense';
  if (low.includes('fancy deep') || low.includes('deep')) return 'Fancy Deep';
  if (low.includes('fancy dark') || low.includes('dark')) return 'Fancy Dark';
  if (low.includes('fancy light')) return 'Fancy Light';
  if (low.includes('very light') || low.includes('faint') || low.includes('light')) return 'Light';
  return 'Fancy';
}

export function extractFancyOvertone(colorText: string): string | undefined {
  const low = colorText.toLowerCase();
  if (low.includes('orangy') || low.includes('оранж')) return 'Оранжевый подтон';
  if (low.includes('purplish') || low.includes('пурпур')) return 'Пурпурный подтон';
  if (low.includes('greenish') || low.includes('зелен')) return 'Зеленоватый подтон';
  if (low.includes('brownish') || low.includes('коричн')) return 'Коричневый подтон';
  if (low.includes('grayish') || low.includes('серов')) return 'Серый подтон';
  if (low.includes('yellowish') || low.includes('желт')) return 'Желтоватый подтон';
  return undefined;
}

export function getFancyDiamondImage(
  color: string,
  colorFamily: string | undefined,
  fallbackShape: DiamondShape
): string {
  const hay = `${color} ${colorFamily || ''}`.toLowerCase();
  if (hay.includes('хамелеон') || hay.includes('chameleon')) {
    return FANCY_IMAGE_MAP.green;
  }
  if (hay.includes('розов') || hay.includes('pink') || hay.includes('rose') || hay.includes('пурпур') || hay.includes('фиолет') || hay.includes('purple') || hay.includes('красн') || hay.includes('red')) {
    return FANCY_IMAGE_MAP.pink;
  }
  if (hay.includes('син') || hay.includes('голуб') || hay.includes('blue') || hay.includes('aqua')) {
    return FANCY_IMAGE_MAP.blue;
  }
  if (hay.includes('зел') || hay.includes('green') || hay.includes('mint')) {
    return FANCY_IMAGE_MAP.green;
  }
  if (hay.includes('жёлт') || hay.includes('желт') || hay.includes('yellow') || hay.includes('canary') || hay.includes('lemon')) {
    return FANCY_IMAGE_MAP.yellow;
  }
  if (hay.includes('коньяч') || hay.includes('шампан') || hay.includes('корич') || hay.includes('brown') || hay.includes('champagne') || hay.includes('cognac') || hay.includes('оранж') || hay.includes('orange')) {
    return FANCY_IMAGE_MAP.cognac;
  }
  return SHAPE_IMAGE_MAP[fallbackShape];
}

export function formatStonePrice(
  amount: number,
  currency: PriceCurrency = 'USD'
): string {
  const formatted = Math.round(amount).toLocaleString('en-US');
  if (currency === 'RUB') return `${formatted} ₽`;
  if (currency === 'EUR') return `€${formatted}`;
  return `$${formatted}`;
}

export function getColorHexTint(
  color: string,
  colorFamily?: string
): { base: string; deep: string; facet: string } {
  const whiteMap: Record<string, string> = {
    D: '#F8FBFF',
    E: '#F9FBFF',
    F: '#FAFBFD',
    G: '#FCFBF7',
    H: '#FCF9F0',
    I: '#FAF5E6',
    J: '#F7F0D9',
  };

  const upper = color.trim().toUpperCase();
  if (whiteMap[upper]) {
    return { base: whiteMap[upper], deep: '#DCE2EC', facet: 'rgba(27, 54, 93, 0.24)' };
  }

  const hay = `${color} ${colorFamily || ''}`.toLowerCase();
  if (hay.includes('хамелеон') || hay.includes('chameleon')) {
    return { base: '#E4EDD9', deep: '#6B8E4E', facet: 'rgba(67, 97, 45, 0.34)' };
  }
  if (hay.includes('розов') || hay.includes('pink') || hay.includes('rose')) {
    return { base: '#FCE4EC', deep: '#E99EB8', facet: 'rgba(173, 20, 87, 0.24)' };
  }
  if (hay.includes('красн') || hay.includes('рубин') || hay.includes('red') || hay.includes('ruby')) {
    return { base: '#FFCDD2', deep: '#C62828', facet: 'rgba(136, 14, 30, 0.34)' };
  }
  if (hay.includes('син') || hay.includes('голуб') || hay.includes('сапфир') || hay.includes('blue') || hay.includes('aqua')) {
    return { base: '#DBEAFE', deep: '#3B82F6', facet: 'rgba(29, 78, 216, 0.32)' };
  }
  if (hay.includes('зел') || hay.includes('изумруд') || hay.includes('green') || hay.includes('mint')) {
    return { base: '#D1FAE5', deep: '#10B981', facet: 'rgba(4, 120, 87, 0.32)' };
  }
  if (hay.includes('жёлт') || hay.includes('желт') || hay.includes('yellow') || hay.includes('canary') || hay.includes('lemon')) {
    return { base: '#FEF3C7', deep: '#F59E0B', facet: 'rgba(180, 83, 9, 0.28)' };
  }
  if (hay.includes('оранж') || hay.includes('orange') || hay.includes('padparadscha')) {
    return { base: '#FFEDD5', deep: '#EA580C', facet: 'rgba(154, 52, 18, 0.28)' };
  }
  if (hay.includes('фиолет') || hay.includes('пурпур') || hay.includes('сирен') || hay.includes('purple') || hay.includes('violet') || hay.includes('amethyst')) {
    return { base: '#EDE9FE', deep: '#8B5CF6', facet: 'rgba(91, 33, 182, 0.30)' };
  }
  if (hay.includes('корич') || hay.includes('brown')) {
    return { base: '#EFE0D1', deep: '#7C4A26', facet: 'rgba(92, 51, 23, 0.32)' };
  }
  if (hay.includes('коньяч') || hay.includes('шампан') || hay.includes('champagne') || hay.includes('cognac')) {
    return { base: '#F5E6D3', deep: '#B48352', facet: 'rgba(120, 74, 36, 0.28)' };
  }
  if (hay.includes('чёрн') || hay.includes('черн') || hay.includes('black')) {
    return { base: '#CBD5E1', deep: '#111827', facet: 'rgba(15, 23, 42, 0.55)' };
  }
  if (hay.includes('сер') || hay.includes('gray') || hay.includes('grey')) {
    return { base: '#E2E8F0', deep: '#94A3B8', facet: 'rgba(71, 85, 105, 0.36)' };
  }

  return { base: '#F5F7FA', deep: '#CBD5E1', facet: 'rgba(27, 54, 93, 0.24)' };
}

export function getCertVerifyUrl(lab: CertLab, certNumber: string): string {
  const cleanNum = encodeURIComponent(certNumber.trim());
  const upper = String(lab).toUpperCase();
  if (upper === 'GIA') {
    return `https://www.gia.edu/report-check?reportno=${cleanNum}`;
  }
  if (upper === 'IGI') {
    return `https://www.igi.org/Verify-Your-Report/?r=${cleanNum}`;
  }
  if (upper === 'HRD') {
    return `https://my.hrdantwerp.com/?record_number=${cleanNum}`;
  }
  if (upper === 'GRS') {
    return `https://www.gemresearch.ch/verify/?report=${cleanNum}`;
  }
  return `https://www.gia.edu/report-check?reportno=${cleanNum}`;
}

